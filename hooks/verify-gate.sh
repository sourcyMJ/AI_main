#!/usr/bin/env bash
# Stop: если в этом ходе менялись файлы, не даём закончить, пока не прогнан verifier.
#
# Защита от зацикливания: флаг снимается сразу, а verifier — read-only агент
# без Edit, поэтому нового флага он не поставит. Если же модель после приёмки
# снова что-то правит, флаг встаёт заново и приёмка повторяется. Это не цикл,
# а ровно то поведение, которое нужно.
set -uo pipefail

DIR="${TMPDIR:-/tmp}/claude-workbench"

SID="$(python3 -c 'import json,sys
try:
    print(json.load(sys.stdin).get("session_id") or "default")
except Exception:
    print("default")' 2>/dev/null)" || SID="default"
[ -n "$SID" ] || SID="default"

FLAG="$DIR/changed-$SID"
[ -f "$FLAG" ] || exit 0
rm -f "$FLAG" 2>/dev/null || true

python3 - <<'PY'
import json
reason = (
    "В этом ходе менялись файлы, а приёмка не прогонялась. "
    "Прежде чем закончить, вызови субагента verifier.\n\n"
    "В задании для него перечисли ПО ПУНКТАМ, что именно ты утверждаешь о своей "
    "работе: какой файл изменён и зачем, что проверено и чем, что осталось "
    "непроверенным. Без такого списка приёмщику не с чем сверять.\n\n"
    "verifier читает не твои рассуждения, а артефакт — код, дифф, вывод команды. "
    "Покажи пользователю его вердикт: принято / принято с замечаниями / не принято, "
    "и каждое расхождение, если оно есть.\n\n"
    "Если verifier недоступен, скажи об этом прямо и не выдавай работу за принятую."
)
print(json.dumps({"decision": "block", "reason": reason}, ensure_ascii=False))
PY
exit 0
